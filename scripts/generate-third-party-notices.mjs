#!/usr/bin/env node
import { spawnSync } from "node:child_process"
import { createHash } from "node:crypto"
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"

const OUTPUT_PATH = resolve("THIRD_PARTY_NOTICES.md")
const CHECK_ONLY = process.argv.includes("--check")
const LICENSE_FILE_PATTERN = /^(?:licen[cs]e|copying|notice)(?:\.|$)/i

const readProductionTree = () => {
  const result = spawnSync(
    "pnpm",
    ["list", "--prod", "--depth", "Infinity", "--json"],
    { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
  )
  if (result.error) throw result.error
  if (result.status !== 0) {
    throw new Error(result.stderr.trim() || "pnpm-production-tree-failed")
  }
  return JSON.parse(result.stdout)
}

const collectPackages = (roots) => {
  const packages = new Map()
  const stack = roots.flatMap((root) => Object.entries(root.dependencies ?? {}))

  while (stack.length) {
    const [name, dependency] = stack.pop()
    if (!dependency || typeof dependency !== "object") continue
    const version = dependency.version
    const directory = dependency.path
    if (typeof version === "string" && typeof directory === "string") {
      packages.set(`${name}@${version}`, { name, version, directory })
    }
    stack.push(...Object.entries(dependency.dependencies ?? {}))
  }

  return packages
}

const readPackageMetadata = ({ directory }) =>
  JSON.parse(readFileSync(join(directory, "package.json"), "utf8"))

const findLicensePath = (directory) => {
  const filename = readdirSync(directory)
    .filter((entry) => LICENSE_FILE_PATTERN.test(entry))
    .sort((left, right) => left.localeCompare(right))[0]
  return filename ? join(directory, filename) : null
}

const normalizeLicenseText = (value) =>
  value
    .replace(/\r\n?/g, "\n")
    .replace(/[ \t]+$/gm, "")
    .trim() + "\n"

const readLicenseText = (key, item, packages) => {
  const directPath = findLicensePath(item.directory)
  if (directPath) return normalizeLicenseText(readFileSync(directPath, "utf8"))

  // react-remove-scroll-bar publishes only dist/constants despite declaring
  // MIT. Its sibling package is maintained by the same author and ships the
  // shared repository's complete MIT notice.
  if (item.name === "react-remove-scroll-bar") {
    const sibling = [...packages.values()].find(
      (candidate) => candidate.name === "react-remove-scroll"
    )
    const siblingPath = sibling && findLicensePath(sibling.directory)
    if (siblingPath) {
      return normalizeLicenseText(readFileSync(siblingPath, "utf8"))
    }
  }

  throw new Error(`${key}: dependency package does not contain a license file`)
}

const groupNotices = (packages) => {
  const groups = new Map()
  for (const [key, item] of [...packages].sort(([left], [right]) =>
    left.localeCompare(right)
  )) {
    const metadata = readPackageMetadata(item)
    const license =
      typeof metadata.license === "string" ? metadata.license : "UNKNOWN"
    const text = readLicenseText(key, item, packages)
    const hash = createHash("sha256").update(text).digest("hex").slice(0, 12)
    const group = groups.get(hash) ?? {
      hash,
      text,
      licenses: new Set(),
      keys: []
    }
    group.licenses.add(license)
    group.keys.push(key)
    groups.set(hash, group)
  }
  return [...groups.values()].sort((left, right) =>
    left.keys[0].localeCompare(right.keys[0])
  )
}

const renderNotices = (packages, groups) => {
  const lines = [
    "# Third-Party Notices",
    "",
    "This file is generated by `pnpm licenses:generate`. It records the",
    "license notices shipped with the production dependency tree used by",
    "TabPlex. Copyright remains with the respective authors.",
    "",
    `Production packages: ${packages.size}. Distinct notices: ${groups.length}.`,
    ""
  ]

  for (const group of groups) {
    lines.push(
      `## ${[...group.licenses].sort().join(" / ")} — ${group.hash}`,
      "",
      ...group.keys.map((key) => `- \`${key}\``),
      "",
      "````text",
      group.text.trimEnd(),
      "````",
      ""
    )
  }

  return lines.join("\n")
}

const packages = collectPackages(readProductionTree())
const notices = renderNotices(packages, groupNotices(packages))

if (CHECK_ONLY) {
  const current = existsSync(OUTPUT_PATH)
    ? readFileSync(OUTPUT_PATH, "utf8")
    : ""
  if (current !== notices) {
    console.error(
      "[TabPlex] THIRD_PARTY_NOTICES.md is stale. Run pnpm licenses:generate."
    )
    process.exit(1)
  }
  console.log(
    `[TabPlex] Third-party notices verified: ${packages.size} packages`
  )
} else {
  writeFileSync(OUTPUT_PATH, notices)
  console.log(
    `[TabPlex] Third-party notices generated: ${packages.size} packages`
  )
}
